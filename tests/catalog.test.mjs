import assert from 'node:assert/strict';
import {OFFICIAL_CATALOG} from '../src/catalog/catalog-data.mjs';
import {normalizeMark,catalogueSearch,documentDateState,validateManualEntry,CATALOG_STORAGE_KEY,exactScannerMatches} from '../src/catalog/catalog-model.mjs';
import {createCatalogStore} from '../src/catalog/catalog-store.mjs';
import {catalogMarkup} from '../src/catalog/catalog-view.mjs';

assert.equal(OFFICIAL_CATALOG.length,20);
assert.equal(new Set(OFFICIAL_CATALOG.map(x=>x.producer)).size,11);
assert.equal(new Set(OFFICIAL_CATALOG.map(x=>x.id)).size,20);
const attestati=OFFICIAL_CATALOG.filter(x=>x.origin==='published-document');
const tecniche=OFFICIAL_CATALOG.filter(x=>x.origin==='technical-sheet');
const storici=OFFICIAL_CATALOG.filter(x=>x.origin==='historical-document');
assert.equal(attestati.length,17);
assert.equal(storici.length,1);
assert.equal(storici[0].validUntil,'2023-12-03');
assert.ok(catalogMarkup(storici,'').includes('ATTESTATO STORICO · SCADUTO'));
assert.ok(!catalogMarkup(storici,'').includes('data-catalog-action="delete"'));
assert.equal(documentDateState(storici[0],'2026-11-24'),'expired-by-date');
assert.equal(tecniche.length,2);
assert.equal(new Set(attestati.map(x=>x.certificate)).size,17);
assert.ok(OFFICIAL_CATALOG.every(x=>/^https:\/\//.test(x.sourceUrl)));
assert.ok(attestati.every(x=>/^\d{4}-\d{2}-\d{2}$/.test(x.validUntil) && /^\d{3}\/\d{2}-CA$/.test(x.certificate)));
assert.ok(tecniche.every(x=>x.certificate===''&&x.validUntil===''));
assert.ok(tecniche.every(x=>x.productKind==='barre'));
assert.equal(OFFICIAL_CATALOG.filter(x=>x.productKind==='barre').length,9);
assert.equal(attestati.filter(x=>x.productKind==='barre').length,6);
assert.equal(OFFICIAL_CATALOG.find(x=>x.certificate==='033/24-CA').markCode,'');
assert.equal(OFFICIAL_CATALOG.find(x=>x.certificate==='004/23-CA').markCode,'0-4-2-5');
assert.equal(OFFICIAL_CATALOG.find(x=>x.certificate==='005/25-CA').productKind,'reti');
assert.equal(normalizeMark('0 · 4 · 2 · 6'),'0-4-2-6');
assert.equal(normalizeMark('0—4—1—9'),'0-4-1-9');
assert.equal(normalizeMark('foo'), '');
assert.equal(catalogueSearch(OFFICIAL_CATALOG,'0 · 4 · 2 · 6')[0].producer,'ALFA ACCIAI S.p.A.');
assert.equal(catalogueSearch(OFFICIAL_CATALOG,'036/23-CA')[0].producer,'FERRIERA VALSABBIA S.p.A.');
assert.equal(catalogueSearch(OFFICIAL_CATALOG,'not-exists').length,0);
assert.equal(documentDateState(OFFICIAL_CATALOG[0],'2029-01-01'),'expired-by-date');
assert.equal(documentDateState(OFFICIAL_CATALOG[0],'2026-11-23'),'within-document-dates');
assert.throws(()=>validateManualEntry({producer:'test',sourceUrl:'javascript:alert(1)'}));
assert.ok(catalogMarkup([{id:'manual-abcdef',origin:'manual',producer:'<img src=x onerror=alert(1)>',markCode:'4-7'}],'').includes('&lt;img'));
const memory=new Map();const fakeStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
const store=createCatalogStore(fakeStorage);
let rec=store.save({producer:'Produttore manuale',markCode:'4-7'});
assert.equal(store.manual().length,1);
assert.equal(store.all().length,21);
assert.equal(store.manual()[0].origin,'manual');
store.save({...rec,producer:'Aggiornato'});
assert.equal(store.manual()[0].producer,'Aggiornato');
const backup=store.exportJson();
assert.equal(JSON.parse(backup).type,'catalog-manual');
store.remove(rec.id);
assert.equal(store.manual().length,0);
assert.equal(store.importJson(backup),1);
assert.equal(store.manual().length,1);
assert.throws(()=>store.remove(OFFICIAL_CATALOG[0].id));
assert.ok(memory.has(CATALOG_STORAGE_KEY));
assert.equal(catalogueSearch(OFFICIAL_CATALOG,'0-4-5')[0].producer,'FERALPI SIDERURGICA S.p.A.');
assert.equal(catalogueSearch(OFFICIAL_CATALOG,'009/23-CA')[0].markCode,'0-3-9');
assert.equal(OFFICIAL_CATALOG.find(x=>x.certificate==='008/23-CA').markCode,'');
assert.equal(OFFICIAL_CATALOG.find(x=>x.certificate==='044/24-CA').productKind,'tralicci');
assert.equal(OFFICIAL_CATALOG.find(x=>x.certificate==='023/18-CA').markCode,'0-4-2-3');
assert.equal(exactScannerMatches(OFFICIAL_CATALOG,'0-4-2-3','2026-11-24').length,0);
assert.equal(exactScannerMatches(OFFICIAL_CATALOG,'0-4-2','2026-11-24').length,0);
assert.equal(exactScannerMatches(OFFICIAL_CATALOG,'0-4-1-7','2026-11-24').length,0);
assert.equal(exactScannerMatches(OFFICIAL_CATALOG,'4-7','2026-11-24').length,0);
assert.equal(exactScannerMatches(OFFICIAL_CATALOG,'0-4-5','2026-11-24').length,1);
assert.equal(exactScannerMatches(OFFICIAL_CATALOG,'0-4-5','2031-01-01').length,0);
assert.ok(!catalogMarkup(tecniche,'').includes('data-catalog-action="delete"'));
assert.ok(catalogMarkup(tecniche,'').includes('NON È ATTESTATO STC'));
assert.equal(documentDateState(tecniche[0]),'unknown');
console.log('TEST CATALOGO: PASS');
